BEGIN;

DROP TABLE IF EXISTS 股市 CASCADE;
DROP TABLE IF EXISTS 市場 CASCADE;

-- 1. 市場資料表
CREATE TABLE 市場 (
    name VARCHAR(20) PRIMARY KEY,       -- 市場指數代號，如 ^TWII
    country VARCHAR(50) NOT NULL        -- 國家/地區，如 台灣
);

-- 2. 股市歷史行情資料表
CREATE TABLE 股市 (
    stock_id SERIAL PRIMARY KEY,
    name VARCHAR(20) REFERENCES 市場(name) ON DELETE CASCADE,
    date DATE NOT NULL,
    open NUMERIC(12, 2),
    high NUMERIC(12, 2),
    low NUMERIC(12, 2),
    close NUMERIC(12, 2),
    adj_close NUMERIC(12, 2),
    volume BIGINT,
    CONSTRAINT unique_market_date UNIQUE (name, date)
);

